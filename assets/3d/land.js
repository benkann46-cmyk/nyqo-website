const boxed = (ring) => {
  const lons = ring.map((p) => p[0]);
  const lats = ring.map((p) => p[1]);
  return { ring, west: Math.min(...lons), east: Math.max(...lons), south: Math.min(...lats), north: Math.max(...lats) };
};
const land = LAND.map(boxed);
const water = WATER.map(boxed);

function inside({ ring, west, east, south, north }, lon, lat) {
  if (lon < west || lon > east || lat < south || lat > north) return false;
  let hit = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [x1, y1] = ring[i];
    const [x2, y2] = ring[j];
    if (y1 > lat !== y2 > lat && lon < ((x2 - x1) * (lat - y1)) / (y2 - y1) + x1) hit = !hit;
  }
  return hit;
}

export function isLand(lon, lat) {
  if (lat < -68 - 3 * Math.sin((lon * Math.PI) / 60)) return true;
  return land.some((shape) => inside(shape, lon, lat)) && !water.some((shape) => inside(shape, lon, lat));
}
